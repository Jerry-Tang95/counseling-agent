export function buildCrisisMessage(level: number): string {
  if (level >= 3) {
    return [
      "我很在意你现在的安全。你描述的像是正在发生的紧急情况。",
      "",
      "请先做一件事：**如果现在有立即危险，请马上拨打 110 或 120**，或者请身边的人陪着你。",
      "如果可能，请把门打开、远离可以伤害自己的物品，去一个有其他人的地方。",
      "",
      "我会在这里陪你，但在确认你安全之前，我们不能继续普通对话。你现在身边有可以联系的人吗？",
    ].join("\n");
  }
  return [
    "谢谢你愿意把这句话说出来。听到这里，我想先停下来，认真问问你的安全。",
    "",
    "**你现在有伤害自己的打算吗？有没有具体的计划或准备？**",
    "",
    "如果有，请先拨打 **110/120**，或联系一个你信任的人来陪你。也可以拨打 **12356** 心理援助热线。",
    "你的安全比继续聊下去更重要。我会在这里，等你告诉我你现在是否安全。",
  ].join("\n");
}

